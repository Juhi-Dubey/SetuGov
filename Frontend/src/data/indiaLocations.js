/**
 * Return all 28 states and 8 union territories sorted
 */
export const getStatesAndUTs = () => STATES_AND_UTS;

/**
 * Return cities for a given state / UT
 */
export const getCitiesForState = (stateName) => {
  if (!stateName || typeof stateName !== 'string') return [];
  return INDIA_LOCATIONS[stateName.trim()] || [];
};

/**
 * Validate if a state / UT exists in canonical list
 */
export const isValidState = (stateName) => {
  if (!stateName || typeof stateName !== 'string') return false;
  return STATES_AND_UTS.includes(stateName.trim());
};

/**
 * Validate if a city belongs to the given state / UT
 */
export const isValidCityForState = (stateName, cityName) => {
  if (!isValidState(stateName)) return false;
  if (!cityName || typeof cityName !== 'string') return false;
  const cities = getCitiesForState(stateName);
  const normalizedCity = cityName.trim().toLowerCase();
  return cities.some(c => c.toLowerCase() === normalizedCity);
};

/**
 * Resolve canonical city name matching case
 */
export const getCanonicalCityName = (stateName, cityName) => {
  if (!isValidState(stateName) || !cityName) return null;
  const cities = getCitiesForState(stateName);
  const normalizedCity = cityName.trim().toLowerCase();
  const match = cities.find(c => c.toLowerCase() === normalizedCity);
  return match || null;
};
